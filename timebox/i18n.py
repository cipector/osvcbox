def current_language(request=None):
    if request is not None:
        language = getattr(request, "LANGUAGE_CODE", None)
        if language in SUPPORTED_LANGUAGES:
            return language
        if hasattr(request, "session"):
            session_language = request.session.get(LANGUAGE_SESSION_KEY)
            if session_language in SUPPORTED_LANGUAGES:
                return session_language
    language = get_language()
    if language in SUPPORTED_LANGUAGES:
        return language
    return DEFAULT_LANGUAGE


def t(language, *path, **kwargs):
    value = TEXTS.get(language, TEXTS[DEFAULT_LANGUAGE])
    for key in path:
        value = value[key]
    if isinstance(value, str) and kwargs:
        return value.format(**kwargs)
    return value


